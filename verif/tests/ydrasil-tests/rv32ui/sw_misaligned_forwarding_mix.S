#include "riscv_test.h"
#include "sw_test_macros.h"

RVTEST_RV32U
RVTEST_CODE_BEGIN
  la s0, mix_bytes

  li t1, 0x11223344
  addi t0, s0, 1
  xori t2, t1, 0
  sw t2, 0(t0)

  li a1, 0x1111
  li a2, 3
  mul t2, a1, a2
  addi t0, s0, 18
  sw t2, 0(t0)

  addi t0, s0, 35
  lw t2, source_word
  sw t2, 0(t0)

  li t1, 0x76543210
  csrw mscratch, t1
  addi t0, s0, 49
  csrrs t2, mscratch, zero
  sw t2, 0(t0)
  csrw mscratch, zero

  lw a0, 1(s0)
  CHECK_EQ_IMM(2, a0, 0x11223344)
  CHECK_BYTE(3, s0, 0, 0xa0)
  CHECK_BYTE(4, s0, 5, 0xa5)

  lw a0, 18(s0)
  CHECK_EQ_IMM(5, a0, 0x00003333)
  CHECK_BYTE(6, s0, 17, 0xb1)
  CHECK_BYTE(7, s0, 22, 0xb6)

  lw a0, 35(s0)
  CHECK_EQ_IMM(8, a0, 0x89abcdef)
  CHECK_BYTE(9, s0, 34, 0xc2)
  CHECK_BYTE(10, s0, 39, 0xc7)

  lw a0, 49(s0)
  CHECK_EQ_IMM(11, a0, 0x76543210)
  CHECK_BYTE(12, s0, 48, 0xd0)
  CHECK_BYTE(13, s0, 53, 0xd5)

  SW_TEST_PASSFAIL
RVTEST_CODE_END

  .data
RVTEST_DATA_BEGIN
  .align 4
mix_bytes:
  .byte 0xa0,0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xa7
  .byte 0xa8,0xa9,0xaa,0xab,0xac,0xad,0xae,0xaf
  .byte 0xb0,0xb1,0xb2,0xb3,0xb4,0xb5,0xb6,0xb7
  .byte 0xb8,0xb9,0xba,0xbb,0xbc,0xbd,0xbe,0xbf
  .byte 0xc0,0xc1,0xc2,0xc3,0xc4,0xc5,0xc6,0xc7
  .byte 0xc8,0xc9,0xca,0xcb,0xcc,0xcd,0xce,0xcf
  .byte 0xd0,0xd1,0xd2,0xd3,0xd4,0xd5,0xd6,0xd7
  .byte 0xd8,0xd9,0xda,0xdb,0xdc,0xdd,0xde,0xdf
source_word:
  .word 0x89abcdef
RVTEST_DATA_END
